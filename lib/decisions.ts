/**
 * Decisions Module
 *
 * Records and compiles human lecturer review decisions:
 * - Pair finding choices: 'dismiss' | 'common_source' | 'flag'
 * - Claim finding choices: 'accept' | 'cite' | 'flag'
 *
 * Provides statistics calculation and Markdown export.
 */

export type FindingType = "pair" | "claim";
export type DecisionChoice =
  | "dismiss"
  | "common_source"
  | "flag"
  | "accept"
  | "cite";

export interface DecisionRecord {
  id: string;
  batch_id: string;
  finding_type: FindingType;
  finding_id: string;
  choice: DecisionChoice;
  note?: string;
  decided_at: string;
}

export interface DecisionsStats {
  total: number;
  dismissed: number;
  common_source: number;
  flagged: number;
  pending: number;
  decided_percentage: number;
}

// In-memory store for local / demo execution when DB is in memory
const inMemoryDecisions: Map<string, DecisionRecord> = new Map();

/**
 * Saves a human reviewer decision for a specific finding.
 */
export function recordDecision(
  batchId: string,
  findingType: FindingType,
  findingId: string,
  choice: DecisionChoice,
  note: string = ""
): DecisionRecord {
  const key = `${batchId}:${findingType}:${findingId}`;
  const record: DecisionRecord = {
    id: `dec-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    batch_id: batchId,
    finding_type: findingType,
    finding_id: findingId,
    choice,
    note,
    decided_at: new Date().toISOString(),
  };

  inMemoryDecisions.set(key, record);
  return record;
}

/**
 * Retrieves a decision for a specific finding if one exists.
 */
export function getDecision(
  batchId: string,
  findingType: FindingType,
  findingId: string
): DecisionRecord | undefined {
  return inMemoryDecisions.get(`${batchId}:${findingType}:${findingId}`);
}

/**
 * Returns all decisions for a given batch.
 */
export function getDecisionsForBatch(batchId: string): DecisionRecord[] {
  const list: DecisionRecord[] = [];
  for (const record of inMemoryDecisions.values()) {
    if (record.batch_id === batchId) {
      list.push(record);
    }
  }
  return list;
}

/**
 * Calculates review summary statistics over findings and decisions.
 */
export function computeDecisionsStats(
  totalFindings: number,
  decisions: DecisionRecord[]
): DecisionsStats {
  let dismissed = 0;
  let common_source = 0;
  let flagged = 0;

  for (const d of decisions) {
    if (d.choice === "dismiss" || d.choice === "accept") {
      dismissed++;
    } else if (d.choice === "common_source") {
      common_source++;
    } else if (d.choice === "flag" || d.choice === "cite") {
      flagged++;
    }
  }

  const decidedTotal = dismissed + common_source + flagged;
  const pending = Math.max(0, totalFindings - decidedTotal);
  const decided_percentage =
    totalFindings > 0 ? Math.round((decidedTotal / totalFindings) * 100) : 0;

  return {
    total: totalFindings,
    dismissed,
    common_source,
    flagged,
    pending,
    decided_percentage,
  };
}

/**
 * Generates an audit-ready Markdown export of the batch review.
 */
export function generateMarkdownExport(
  batchName: string,
  stats: DecisionsStats,
  flaggedItems: Array<{
    type: FindingType;
    label: string;
    choice: string;
    note?: string;
    detail: string;
  }>
): string {
  const timestamp = new Date().toISOString().replace("T", " ").slice(0, 19);

  let md = `# Margin Review Summary: ${batchName}\n\n`;
  md += `**Date:** ${timestamp} UTC\n`;
  md += `**Reviewer:** Lecturer\n`;
  md += `**System Notice:** Margin flags findings for human evaluation; it never issues an automated verdict.\n\n`;

  md += `## Review Statistics\n\n`;
  md += `| Category | Count |\n`;
  md += `| :--- | :--- |\n`;
  md += `| Total Findings | ${stats.total} |\n`;
  md += `| Dismissed / Accepted | ${stats.dismissed} |\n`;
  md += `| Common Source Recognized | ${stats.common_source} |\n`;
  md += `| Flagged for Follow-up | ${stats.flagged} |\n`;
  md += `| Pending Lecturer Decision | ${stats.pending} |\n`;
  md += `| Review Completion | ${stats.decided_percentage}% |\n\n`;

  md += `## Flagged Items for Follow-up (${flaggedItems.length})\n\n`;

  if (flaggedItems.length === 0) {
    md += `*No items were flagged for follow-up in this batch.*\n`;
  } else {
    flaggedItems.forEach((item, idx) => {
      md += `### ${idx + 1}. [${item.type.toUpperCase()}] ${item.label}\n`;
      md += `- **Decision:** ${item.choice.toUpperCase()}\n`;
      if (item.note) {
        md += `- **Lecturer Note:** ${item.note}\n`;
      }
      md += `- **Finding Detail:** ${item.detail}\n\n`;
    });
  }

  md += `---\n*Generated by Margin · Academic Integrity Review System*\n`;
  return md;
}
